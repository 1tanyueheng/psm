"""One diagram, with role-specific arrows on the profile classes.

Two instructions from the user, and they pull in different directions:

  * **one figure** — the thesis does not permit two class diagrams;
  * **relations attach to the normalised class, not `User`** — which is what makes
    one figure readable.

The second is only honest where a foreign key names a *role*, not merely *a
person*. Of the 22 arrows into `users`, five do:

    evaluations.assessor_id          an assessor is a supervisor
    examiner_assignments.examiner_id an examiner is seated from supervisors
    examiner_pairs.examiner_1_id     ditto
    examiner_pairs.examiner_2_id     ditto
    sections.lecturer_id             a section's teacher is staff

The other seventeen are `created_by`, `approved_by`, `locked_by` and friends: the
actor may be an admin, so drawing them on `SupervisorProfile` would be a lie in a
figure whose whole point is describing the schema. **They stay on `User`.**

So the combined figure re-targets five arrows and keeps seventeen. That is a real
improvement — the assessment chain no longer runs to the identity table — but it
is not the "move everything off User" that was asked for, and the difference is
listed here rather than hidden.

Writes `thesis/diagrams/class_diagram.txt` (Mermaid) and the `.drawio` is rebuilt
by `make_class_drawio.py` from the same relations.
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import make_class_diagram as gen  # noqa: E402

BASE = r"C:\Users\yuehe\Desktop\study\fyp\AIProject\psm-system"
DIA = os.path.join(BASE, "thesis", "diagrams")

# The five relations that name a role rather than an actor, by label as it
# appears in `make_class_diagram.RELATIONS`.
#   (label) -> (new left class, new cardinality, new label)
RETARGET = {
    "assesses":                ("SupervisorProfile", "||--o{", "assesses"),
    "examines":                ("SupervisorProfile", "||--o{", "examines"),
    "lectures":                ("SupervisorProfile", "||--o{", "lectures"),
    "examiner 1 / examiner 2": ("SupervisorProfile", "2 -- 1", "examiner 1 / 2"),
}

# Where an arrow being re-pointed was ALSO carrying an actor column, that actor
# column gets its own arrow back to `User`. Without this the redirect makes the
# diagram *less* complete: `examiner_pairs` would show its examiners and lose
# the person who created the pair.
ACTOR_ALSO = {
    "ExaminerPair": "created by *",
    "ExaminerAssignment": "assigned by *",
}


def combined_relations():
    """The relation list with the four role-specific arrows re-pointed.

    **Two arrows are added rather than moved.** `examiner_pairs` and
    `examiner_assignments` each had ONE arrow to `User`, covering both their
    examiner column (a supervisor) and their actor column (`created_by`,
    `assigned_by`, anyone). Re-pointing that single arrow to `SupervisorProfile`
    would leave the actor column undrawn — which is what happened on the first
    attempt, and the checker caught it.

    So each gains a second arrow: the examiner link goes to the profile, and the
    actor link stays on `User`. A row has a person on each side and the diagram
    now says so, instead of one arrow standing for both.
    """
    out = []

    for rel in gen.RELATIONS:
        left, card, spare, right, label, kind = rel

        if label in RETARGET and left == "User":
            new_left, new_card, new_label = RETARGET[label]

            if new_card == "2 -- 1":
                out.append((new_left, "2", "==", right, new_label, "assoc"))
            else:
                out.append((new_left, new_card, "", right, new_label, "assoc"))

            # The actor column that used to share this arrow.
            actor_label = ACTOR_ALSO.get(right)
            if actor_label:
                out.append(("User", "|o--o{", "", right, actor_label, "assoc"))
            continue

        out.append(rel)

    return out


THEME = """%%{init: {
  'theme': 'base',
  'themeVariables': {
    'fontFamily': 'Times New Roman, serif',
    'fontSize': '12px',
    'primaryColor': '#ffffff',
    'primaryTextColor': '#1a1a1a',
    'primaryBorderColor': '#1a1a1a',
    'lineColor': '#333333',
    'edgeLabelBackground': '#ffffff'
  }
}}%%
classDiagram
    direction TB
"""


def render(relations):
    drawn = set()
    out = [
        "%% Figure 4.14 - PSM Assessment System class diagram.",
        "%% One figure, as the thesis requires. Role-specific associations attach",
        "%% to StudentProfile / SupervisorProfile where the foreign key names a",
        "%% role; the `*_by` columns stay on User because their actor may be",
        "%% anyone. Generated by .workbuddy-ai/make_class_diagram_combined.py.",
        "",
        THEME.rstrip(),
        "",
    ]

    for alias, table, uc, group in gen.CLASSES:
        if alias in drawn:
            continue

        out.append(f"    %% {uc} - {group} - table `{table}`")
        out.append(f"    class {alias}{{")
        for member in gen.ATTRIBUTES[alias]:
            out.append(f"        {member}")
        out.append("    }")
        out.append("")
        drawn.add(alias)

    out.append("    %% ---- Associations ----")
    out.append("    %% Every arrow is a foreign key. `*` marks a row where several")
    out.append("    %% columns point at the same class.")
    out.append("")

    for left, card, spare, right, label, kind in relations:
        if kind == "inherit":
            out.append(f"    {right} <|-- {left} : {label}")
            continue

        # The two-foreign-keys case. Written by hand because neither cardinality
        # map has a "two" in it, and `2 -- 1` is not Mermaid syntax — it parses as
        # nothing and the arrow silently disappears.
        if spare == "==":
            out.append(f'    {left} "2" --> "1" {right} : {label}')
            continue

        left_card, right_card = gen.C[card]
        arrow = {"assoc": "-->", "comp": "*--", "agg": "o--"}.get(kind, "-->")
        out.append(f'    {left} "{left_card}" {arrow} "{right_card}" {right} : {label}')

    out.append("")
    return "\n".join(out)


def main():
    relations = combined_relations()

    # Counted by *relation*, not by label: `lectures` is written once on User
    # (redirected here) and the label set therefore says nothing about how many
    # arrows moved.
    on_user = sum(1 for left, *_rest in gen.RELATIONS if left == "User")
    after = sum(1 for left, *_rest in relations if left == "User")
    moved = len(RETARGET)
    added = sum(1 for v in ACTOR_ALSO.values())

    path = os.path.join(DIA, "class_diagram.txt")
    io.open(path, "w", encoding="utf-8", newline="\n").write(render(relations))

    print(f"classes   : {len(gen.CLASSES)}")
    print(f"relations : {len(relations)}  ({moved + added} more than the original "
          f"{len(gen.RELATIONS)} - the redirected arrows were also carrying actors)")
    print()
    print(f"arrows re-pointed to SupervisorProfile : {moved}")
    for label in sorted(RETARGET):
        print(f"   {label}")
    print()
    print(f"actor arrows added back to User : {added}")
    for target, label in ACTOR_ALSO.items():
        print(f"   {target:22} {label}")
    print()
    print(f"arrows on User : {on_user} -> {after}")
    print("   the remainder are `*_by` columns; their actor may be an admin, so")
    print("   drawing them on a profile class would misdescribe the schema")
    print(f"wrote {path}")


def write_drawio():
    """The .drawio must come from the SAME re-pointed list as the Mermaid."""
    import make_class_drawio

    make_class_drawio.main(
        classes=gen.CLASSES,
        relations=combined_relations(),
        out=os.path.join(DIA, "class_diagram.drawio"),
        title="4.14 Class diagram - PSM Assessment System",
    )


if __name__ == "__main__":
    main()
    print()
    write_drawio()
