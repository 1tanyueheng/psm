"""Split Figure 4.14 into two readable figures.

The diagram is messy because `users` is the hub of 22 foreign keys — that is the
schema, not a drawing fault. The remedy is two figures at print width rather
than one unreadable one:

  * **4.14a People**        — who exists, and how the roles attach to a person
  * **4.14b Project work**  — the lifecycle: registration, chain, assessment, result

**`users` appears in both**, and that is the seam, not an accident. A figure per
"the people" and "the work" needs the person in both, and the cross-references
between them are named in each figure's header rather than drawn as 8 long arrows
that would defeat the split.

This script does not re-declare anything: it **partitions** `make_class_diagram`'s
classes and relations by whether the table is about a person. A relation stays in
a figure when both its ends are in that figure; the rest are listed as
cross-references.

Writes:
  thesis/diagrams/class_people.txt        (4.14a)
  thesis/diagrams/class_project_work.txt  (4.14b)
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import make_class_diagram as gen  # noqa: E402

BASE = r"C:\Users\yuehe\Desktop\study\fyp\AIProject\psm-system"
DIA = os.path.join(BASE, "thesis", "diagrams")

# Which tables belong to "the people" figure.
PEOPLE_TABLES = {
    "users", "student_profiles", "supervisor_profiles",
    "coordinator_scopes", "sections", "lecturer_marks",
    "student_enrolments",
}

# **`users` is drawn in BOTH figures.** Splitting the diagram puts the seam
# straight through it — 16 of the 22 arrows into `users` come from the work side
# (`created_by`, `approved_by`, `locked_by`, renamed…). Listing those 16 as
# "see the other figure" prose makes two figures that each need the other open,
# which is the problem the split was meant to solve.
#
# Drawing `User` in both figures instead turns every one of them into a real
# arrow in the figure that needs it. The cost is one repeated box and a note
# saying so — the same convention as showing a database context in more than one
# diagram.
SHARED = {"users"}

THEME = """%%{init: {
  'theme': 'base',
  'themeVariables': {
    'fontFamily': 'Times New Roman, serif',
    'fontSize': '13px',
    'primaryColor': '#ffffff',
    'primaryTextColor': '#1a1a1a',
    'primaryBorderColor': '#1a1a1a',
    'lineColor': '#333333',
    'edgeLabelBackground': '#ffffff'
  }
}}%%
classDiagram
    direction TB
"""


def render(title, comment, aliases, relations, cross_refs):
    table_of = {a: t for a, t, _uc, _g in gen.CLASSES}
    out = [
        f"%% {title}",
        f"%% {comment}",
        "%%",
        "%% Generated by .workbuddy-ai/split_class_diagram.py from",
        "%% make_class_diagram.py, so both figures describe the same schema.",
        "%% Every arrow is a foreign key.",
        "",
        THEME.rstrip(),
        "",
    ]

    # --- classes, in the use-case order the generator uses ----------------
    drawn = set()
    for alias, table, uc, group in gen.CLASSES:
        if alias not in aliases or alias in drawn:
            continue

        out.append(f"    %% {uc} - {group} - table `{table}`")
        out.append(f"    class {alias}{{")
        for member in gen.ATTRIBUTES[alias]:
            out.append(f"        {member}")
        out.append("    }")
        out.append("")
        drawn.add(alias)

    # --- relations whose both ends are in this figure ---------------------
    out.append("    %% ---- Associations ----")
    out.append("")

    for rel in relations:
        left, card, spare, right, label, kind = rel

        if kind == "inherit":
            out.append(f"    {right} <|-- {left} : {label}")
            continue

        if card == "2" and spare == "||":
            out.append(f'    {left} "2" --> "1" {right} : {label}')
            continue

        left_card, right_card = gen.C[card]
        arrow = {"assoc": "-->", "comp": "*--", "agg": "o--"}.get(kind, "-->")
        out.append(f'    {left} "{left_card}" {arrow} "{right_card}" {right} : {label}')

    # --- the seam ---------------------------------------------------------
    if cross_refs:
        out.append("")
        out.append("    %% ---- Continues in the other figure ----")
        for ref in cross_refs:
            out.append(f"    %% {ref}")

    out.append("")
    return "\n".join(out)


def main():
    table_of = {a: t for a, t, _uc, _g in gen.CLASSES}

    shared = {a for a, t in table_of.items() if t in SHARED}
    people_only = {a for a, t in table_of.items() if t in PEOPLE_TABLES} - shared
    work_only = set(table_of) - people_only - shared

    people = people_only | shared
    work = work_only | shared

    people_rels, work_rels, cross = [], [], []

    for rel in gen.RELATIONS:
        left, _card, _spare, right, label, _kind = rel
        in_people = left in people and right in people
        in_work = left in work and right in work

        # A relation is drawn wherever BOTH its ends are drawn. Because `User`
        # is in both figures, a seam only remains when one end belongs to a role
        # profile — `StudentProfile -- StudentEnrolment` is fine in the people
        # figure, but `Project -- ProjectMember -- StudentProfile` is not.
        if in_people:
            people_rels.append(rel)
        if in_work:
            work_rels.append(rel)
        if not in_people and not in_work:
            cross.append(rel)

    people_cross, work_cross = [], []
    for rel in cross:
        left, _card, _spare, right, label, _kind = rel
        (people_cross if left in people else work_cross).append(
            f"{left} --({label})-- {right}  [drawn in the other figure]")

    p1 = os.path.join(DIA, "class_people.txt")
    io.open(p1, "w", encoding="utf-8", newline="\n").write(render(
        "Figure 4.14a - PSM Assessment System: people and access",
        "Who exists, and what the two roles with data of their own hold.",
        people, people_rels, people_cross,
    ))

    p2 = os.path.join(DIA, "class_project_work.txt")
    io.open(p2, "w", encoding="utf-8", newline="\n").write(render(
        "Figure 4.14b - PSM Assessment System: project work and assessment",
        "The lifecycle, from registration to the released mark.",
        work, work_rels, work_cross,
    ))

    print(f"4.14a people : {len(people):2} classes, {len(people_rels):2} relations, "
          f"{len(people_cross):2} cross-references")
    print(f"4.14b work   : {len(work):2} classes, {len(work_rels):2} relations, "
          f"{len(work_cross):2} cross-references")
    print(f"User is drawn in both; every other class in exactly one.")
    print(f"relations drawn somewhere: {len(people_rels | set(work_rels) if False else set(map(id, people_rels + work_rels)))}")
    print(f"relations in total        : {len(gen.RELATIONS)}")
    print(f"wrote {p1}")
    print(f"wrote {p2}")


if __name__ == "__main__":
    main()
